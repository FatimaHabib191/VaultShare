// Generates public/js/icons.js from the Lucide icon set (ISC licence).
// Only the icons the interface uses are included, as plain data, so there is no
// runtime dependency and no inline SVG markup (icons are built with createElementNS).
//   node scripts/build/icons.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const NAMES = {
  dashboard: 'layout-dashboard', files: 'files', upload: 'upload', 'upload-cloud': 'cloud-upload', history: 'history', user: 'user-round',
  users: 'users', settings: 'sliders-horizontal', audit: 'scroll-text', decisions: 'list-checks', trace: 'scan-search', overview: 'gauge',
  logout: 'log-out', menu: 'menu', x: 'x', search: 'search', grid: 'layout-grid', list: 'list', 'chevron-down': 'chevron-down',
  'chevron-right': 'chevron-right', 'arrow-left': 'arrow-left', 'file': 'file', 'file-text': 'file-text', 'file-image': 'file-image',
  'file-sheet': 'file-spreadsheet', 'file-pdf': 'file-type', check: 'check', 'check-circle': 'circle-check', 'x-circle': 'circle-x',
  alert: 'triangle-alert', info: 'info', shield: 'shield-check', 'shield-alert': 'shield-alert', lock: 'lock', unlock: 'lock-open',
  key: 'key-round', share: 'share-2', download: 'download', trash: 'trash-2', eye: 'eye', 'eye-off': 'eye-off', copy: 'copy',
  clock: 'clock', refresh: 'refresh-cw', plus: 'plus', 'user-plus': 'user-plus', ban: 'ban', link: 'link-2', fingerprint: 'fingerprint',
  activity: 'activity', inbox: 'inbox', 'more': 'ellipsis', filter: 'list-filter', 'export': 'file-down', 'sign-in': 'log-in',
  hash: 'hash', alert2: 'circle-alert', loader: 'loader-circle', mail: 'mail', 'user-check': 'user-check', droplet: 'stamp', server: 'server',
};
const out = {};
for (const [name, file] of Object.entries(NAMES)) {
  const mod = await import(pathToFileURL(path.join(ROOT, 'node_modules/lucide/dist/esm/icons', `${file}.js`)).href);
  out[name] = mod.default[2].map(([tag, attrs]) => [tag, attrs]);
}
const header = '// Generated by scripts/build/icons.mjs from Lucide v0.460.0 (ISC licence). Do not edit by hand.\n';
fs.writeFileSync(path.join(ROOT, 'public/js/icons.js'), `${header}export const ICONS = ${JSON.stringify(out)};\n`);
console.log(`wrote ${Object.keys(out).length} icons`);
